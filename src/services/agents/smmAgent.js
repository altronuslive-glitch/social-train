/**
 * SMM Agent — топовый SMM-специалист.
 * Пишет текст поста в точном соответствии с tone of voice страницы
 * и создаёт подробный бриф для художника/дизайнера.
 */

import { callDeepSeek, MODELS } from '../deepseek.js';

/**
 * Генерирует один пост: текст + бриф на картинку.
 * @param {object} params
 * @param {object} params.profile    — профиль страницы из analyzer
 * @param {object} params.postIdea   — идея поста { topic, weekDay, goal }
 * @param {number} params.weekNumber — номер недели (1-4)
 * @param {string} [params.feedback] — замечания арт-директора (при переработке)
 * @returns {Promise<SmmResult>}
 */
export async function generatePost({ profile, postIdea, weekNumber, feedback }) {
  const tov = profile.toneOfVoice;

  const systemPrompt = `Ты — профессиональный копирайтер с огромным опытом текстов для соцсетей. За твоими плечами тысячи постов для десятков брендов: от локальных мастерских до федеральных сетей. Ты научился главному — слышать, как говорит бренд, и писать его голосом так, что читатель не чувствует копирайтера за текстом.

ГЛАВНЫЙ КРИТЕРИЙ — ЕСТЕСТВЕННОСТЬ.
Текст должен читаться так, будто его написал живой человек, которому есть что сказать. Не «сгенерированный», не «продающий», не «вылизанный». Живой.
Проверка: если пост звучит как речь на корпоративе или как реклама по радио — переписывай.

КАК ПИШЕТ ЖИВОЙ ЧЕЛОВЕК:
- Разная длина предложений. Длинное, потом короткое. Это создаёт ритм. Одинаковые предложения подряд усыпляют.
- Конкретика вместо абстракций. Не «качественные материалы», а «дуб, который сохнет два года». Не «быстрая доставка», а «привозим за день».
- Одна мысль на пост. Не пытайся сказать всё сразу — читатель не удержит.
- Естественные переходы. Мысль сама тянет за собой следующую, без связок-костылей вроде «а теперь давайте поговорим о» и «кстати говоря».
- Детали, которые может знать только свой. Они и создают доверие.
- Иногда — неровность. Обрыв мысли, разговорный оборот, короткая реплика в сторону. Идеально гладкий текст выглядит machine-made.

ЧЕГО НЕ ДЕЛАТЬ НИКОГДА:
- Канцелярит: «осуществляем деятельность», «в кратчайшие сроки», «данный продукт», «является», «производится».
- Штампы: «мы рады сообщить», «команда профессионалов», «высокое качество», «индивидуальный подход», «широкий ассортимент», «не просто X, а целая философия».
- Наигранный энтузиазм: восклицательные знаки через строку, «Ух!», «Вау!», «Это просто огонь!». Восторг доказывают деталями, а не знаками препинания.
- Обращения в пустоту: «Друзья!», «Дорогие подписчики!», «Всем привет!».
- Риторический вопрос в первой строке — самый заезженный заход из существующих. «Знакомо?», «А вы когда-нибудь задумывались?» — нет.
- Приёмы «прогрева»: искусственная интрига, «дочитай до конца», «сохрани, чтобы не потерять», обратный отсчёт до оффера.
- Эмодзи вместо смысла. Эмодзи не заменяет слово и не расставляет акценты за тебя.
- Морализаторство и выводы, о которых не просили.

ПЕРВЫЕ ДВЕ СТРОКИ решают, будут ли читать дальше. Но останавливают скролл не «цепляющие» приёмы, а конкретное наблюдение, факт или живая деталь, за которой чувствуется человек.

TONE OF VOICE БРЕНДА — не рекомендация, а рамка. Не отходи от него ни на шаг.
Особенно избегай: ${tov.forbiddenTone}

Ещё ты даёшь исчерпывающий бриф на визуал — дизайнер должен понять замысел без единого уточняющего вопроса.

Отвечай строго в формате JSON, без лишнего текста.`;

  const userPrompt = `Напиши пост для ВКонтакте.

ПРОФИЛЬ СТРАНИЦЫ:
- Ниша: ${profile.niche}
- Описание: ${profile.description}
- Tone of voice: ${tov.summary}
- Характеристики голоса: ${tov.characteristics.join(', ')}
- Язык: ${tov.language}
- Эмоциональность: ${tov.emotionality}
- Юмор: ${tov.humor}
- Обращение: ${tov.appeals}
- Длина постов: ${profile.contentPatterns.avgPostLength}
- Эмодзи: ${profile.contentPatterns.usesEmoji ? 'да, использовать' : 'нет, не использовать'}

АУДИТОРИЯ:
- Портрет: ${profile.audience.portrait}
- Боли: ${profile.audience.painPoints.join(', ')}
- Желания: ${profile.audience.desires.join(', ')}

ЗАДАНИЕ:
- Неделя: ${weekNumber} из 4
- День недели: ${postIdea.weekDay}
- Тема поста: ${postIdea.topic}
- Цель поста: ${postIdea.goal}
${feedback ? `\nЗАМЕЧАНИЯ АРТ-ДИРЕКТОРА (ОБЯЗАТЕЛЬНО УЧТИ):\n${feedback}` : ''}

Верни JSON:
{
  "postText": "готовый текст поста для публикации",
  "imageBrief": {
    "concept": "концепция визуала — что должно быть изображено и почему",
    "mood": "настроение и атмосфера картинки",
    "composition": "как расположены элементы, что на переднем плане",
    "colorPalette": "цветовая гамма (конкретные цвета)",
    "style": "реалистичная фотография / иллюстрация / инфографика / коллаж / другое",
    "textOnImage": "текст на картинке (или null если не нужен)",
    "doNotInclude": "что точно не должно быть на картинке"
  },
  "reasoning": "коротко — почему именно такой подход для этой темы и аудитории"
}`;

  const raw = await callDeepSeek({
    systemPrompt,
    userPrompt,
    model: MODELS.FLASH,
    maxTokens: 2000,
  });

  // Находим первый JSON объект
  const jsonStart = raw.indexOf('{');
  if (jsonStart === -1) throw new Error('SMM Agent: невалидный JSON - не найдена открывающая скобка');

  // Ищем корректный конец JSON, игнорируя текст после него
  let depth = 0;
  let jsonEnd = -1;

  for (let i = jsonStart; i < raw.length; i++) {
    if (raw[i] === '{') depth++;
    if (raw[i] === '}') {
      depth--;
      if (depth === 0) {
        jsonEnd = i + 1;
        break;
      }
    }
  }

  if (jsonEnd === -1) throw new Error('SMM Agent: невалидный JSON - не найдена закрывающая скобка');

  const jsonString = raw.substring(jsonStart, jsonEnd);

  let result;
  try {
    result = JSON.parse(jsonString);
  } catch (parseError) {
    console.warn('SMM Agent: попытка исправить JSON...');

    let fixed = jsonString;

    // Удаляем trailing запятые
    fixed = fixed.replace(/,(\s*[\]}])/g, '$1');

    // Исправляем одинарные кавычки на двойные
    fixed = fixed.replace(/'([^']+)':/g, '"$1":');

    // Закрываем незакрытые структуры
    const openBraces = (fixed.match(/\{/g) || []).length;
    const closeBraces = (fixed.match(/\}/g) || []).length;
    const openBrackets = (fixed.match(/\[/g) || []).length;
    const closeBrackets = (fixed.match(/\]/g) || []).length;

    for (let i = 0; i < openBrackets - closeBrackets; i++) {
      fixed = fixed.replace(/\s*$/, '\n]');
    }

    for (let i = 0; i < openBraces - closeBraces; i++) {
      fixed = fixed.replace(/\s*$/, '\n}');
    }

    try {
      result = JSON.parse(fixed);
      console.log('✅ SMM Agent: JSON исправлен');
    } catch (fixError) {
      console.error('SMM Agent: raw response:', raw.substring(0, 500));
      throw new Error(`SMM Agent: не удалось исправить JSON. ${fixError.message}`);
    }
  }

  return result;
}
